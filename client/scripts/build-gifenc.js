// Bundle the GIF encoder that cropped animated pictures are written with into one ES module.
//
//   npm run build:gifenc
//
// See vendor-src/gifenc.js for why this exists. Writes src/renderer/gifenc.js, which is committed.

const fs = require('node:fs');
const path = require('node:path');
const { buildSync } = require('esbuild');

const ROOT = path.join(__dirname, '..');
const { version } = JSON.parse(fs.readFileSync(path.join(ROOT, 'node_modules', 'gifenc', 'package.json'), 'utf8'));

buildSync({
  entryPoints: [path.join(ROOT, 'vendor-src', 'gifenc.js')],
  outfile: path.join(ROOT, 'src', 'renderer', 'gifenc.js'),
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2022',
  legalComments: 'inline',
  banner: {
    js: [
      '// GENERATED by scripts/build-gifenc.js from vendor-src/gifenc.js: do not edit.',
      `// Bundled: gifenc ${version}. MIT License, (c) Matt DesLauriers (https://github.com/mattdesl/gifenc).`,
    ].join('\n'),
  },
});
console.log(`bundled gifenc ${version}`);
