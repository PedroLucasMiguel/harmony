// `node scripts/make-ui-icons.js` -- the UI's icons, from Phosphor.
//
// Phosphor's "fill" set (MIT, @phosphor-icons/core) is the closest open set
// to Discord's: solid, rounded glyphs that read at 16 px. Only the icons
// named below are copied, into src/renderer/icons/, and icons.css is written
// beside them -- one rule per icon:
//
//   [data-icon="microphone"] { --icon: url("icons/microphone.svg"); }
//
// The generic rule in styles.css draws [data-icon] as a mask over
// currentColor, so every icon is the colour of the text around it and
// follows the palette. Outputs are committed: building the app needs
// neither this script nor the package.
//
// To add an icon: put its Phosphor name in ICONS, run this, use
// data-icon="<name>" (or setIcon in app.js).

const fs = require('node:fs');
const path = require('node:path');

const ICONS = [
  // the call
  'microphone', 'microphone-slash', 'headphones', 'speaker-slash', 'gear-six',
  'phone-disconnect', 'phone-x', 'video-camera', 'video-camera-slash', 'camera-rotate',
  'screencast', 'music-notes',
  // channels and the bar
  'hash', 'speaker-high', 'speaker-x', 'plus', 'users', 'user-circle', 'globe', 'sign-out', 'monitor', 'list',
  // the composer and messages
  'plus-circle', 'smiley', 'paper-plane-right', 'x', 'download-simple',
  'pencil-simple', 'push-pin', 'trash', 'arrow-bend-up-left',
  // tiles and players
  'eye', 'eye-slash', 'squares-four', 'corners-out', 'arrows-out', 'arrows-in', 'scissors',
  'play', 'pause',
];

// By path: the package's exports map hides package.json.
const SOURCE = path.join(__dirname, '..', 'node_modules', '@phosphor-icons', 'core');
const OUT = path.join(__dirname, '..', 'src', 'renderer', 'icons');

fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(OUT, { recursive: true });

const rules = [];
for (const name of ICONS) {
  const file = path.join(SOURCE, 'assets', 'fill', `${name}-fill.svg`);
  fs.copyFileSync(file, path.join(OUT, `${name}.svg`));
  rules.push(`[data-icon='${name}'] { --icon: url('icons/${name}.svg'); }`);
}

fs.writeFileSync(
  path.join(__dirname, '..', 'src', 'renderer', 'icons.css'),
  '/* Generated by scripts/make-ui-icons.js -- Phosphor icons (MIT). Do not edit. */\n'
    + `${rules.join('\n')}\n`,
);
console.log(`[icons] ${ICONS.length} icons -> src/renderer/icons/`);
