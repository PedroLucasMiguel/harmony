// Bundle the cryptography private conversations use into one ES module.
//
//   npm run build:noble
//
// See vendor-src/noble.js for why this exists. Writes src/renderer/noble.js,
// which is committed.

const fs = require('node:fs');
const path = require('node:path');
const { buildSync } = require('esbuild');

const ROOT = path.join(__dirname, '..');
const versions = ['@noble/curves', '@noble/ciphers', '@noble/hashes']
  // Read as files: these packages do not export their package.json.
  .map((name) => `${name} ${JSON.parse(fs.readFileSync(path.join(ROOT, 'node_modules', name, 'package.json'), 'utf8')).version}`)
  .join(', ');

buildSync({
  entryPoints: [path.join(ROOT, 'vendor-src', 'noble.js')],
  outfile: path.join(ROOT, 'src', 'renderer', 'noble.js'),
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2022',
  legalComments: 'inline',
  banner: {
    js: [
      '// GENERATED by scripts/build-noble.js from vendor-src/noble.js: do not edit.',
      `// Bundled: ${versions}. MIT License, (c) Paul Miller (https://paulmillr.com).`,
      '// https://github.com/paulmillr/noble-curves, noble-ciphers and noble-hashes',
    ].join('\n'),
  },
});
console.log(`bundled ${versions}`);
